// The receipt for a paid subscription invoice (a plan, a renewal, add-ons or a
// top-up): a PDF tax invoice attached to an email with the same lines, sent to
// the workspace's owners and billing people the moment a payment is recorded.
// The numbers are the invoice's own — nothing is recalculated here.
import { readFile } from "node:fs/promises";
import path from "node:path";
import fontkit from "@pdf-lib/fontkit";
import { and, eq, inArray } from "drizzle-orm";
import { PDFDocument, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import { db, schema } from "@/db";
import { money } from "@/lib/billing/catalog";
import { settings } from "../platform/settings";
import { appUrl, sendMail } from "../services/mail";

type Invoice = typeof schema.subscriptionInvoices.$inferSelect;

const VIA: Record<string, string> = { razorpay: "Razorpay", stripe: "Stripe", manual: "Bank transfer", credit: "Account credit" };
const KIND: Record<string, string> = { first: "Plan", renewal: "Renewal", upgrade: "Plan change", topup: "Top-up", manual: "Invoice" };
const day = (d: Date | null) => (d ? d.toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric", timeZone: "Asia/Kolkata" }) : "—");

let fontBytes: Promise<Buffer> | null = null;
const font = () => (fontBytes ??= readFile(path.join(process.cwd(), "src/server/invoicing/fonts/Geist-Regular.ttf")));

/** Characters the font can't draw become "?" rather than failing the file. */
const clean = (f: PDFFont, s: string) => {
  const g = new Set(f.getCharacterSet());
  return [...s].map((c) => (g.has(c.codePointAt(0)!) ? c : "?")).join("");
};

export type Seller = { name: string; address: string; gstin: string; email: string };

/** The receipt as a PDF (A4). */
export async function receiptPdf(inv: Invoice, number: string, buyer: string, seller: Seller): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.registerFontkit(fontkit);
  const f = await pdf.embedFont(await font(), { subset: true });
  const page: PDFPage = pdf.addPage([595.28, 841.89]);
  const ink = rgb(0.07, 0.07, 0.07);
  const soft = rgb(0.42, 0.42, 0.45);
  const line = rgb(0.88, 0.88, 0.9);
  const L = 48;
  const R = 595.28 - 48;
  let y = 841.89 - 56;
  const text = (s: string, x: number, size = 10, color = ink, right = false) => {
    const t = clean(f, s);
    page.drawText(t, { x: right ? x - f.widthOfTextAtSize(t, size) : x, y, size, font: f, color });
  };
  const rule = () => page.drawLine({ start: { x: L, y: y + 8 }, end: { x: R, y: y + 8 }, thickness: 0.6, color: line });

  text("Cloudesk", L, 20);
  text(inv.status === "paid" ? "PAID" : inv.status.toUpperCase(), R, 11, rgb(0.12, 0.55, 0.36), true);
  y -= 18;
  text("Tax invoice and receipt", L, 10, soft);
  text(number, R, 11, ink, true);
  y -= 30;
  // Who and when.
  const cols: [string, string[]][] = [
    ["Billed to", [buyer]],
    ["From", [seller.name || "Cloudesk", ...(seller.address ? seller.address.split(/\n|, /).slice(0, 3) : []), ...(seller.gstin ? [`GSTIN ${seller.gstin}`] : [])]],
    ["Paid", [day(inv.paidAt), VIA[inv.paidVia ?? ""] ?? "", ...(inv.paymentRef && inv.paidVia !== "credit" ? [inv.paymentRef] : [])].filter(Boolean)],
  ];
  const w = (R - L) / 3;
  const top = y;
  let low = y;
  cols.forEach(([h, rows], i) => {
    y = top;
    text(h.toUpperCase(), L + i * w, 8, soft);
    for (const r of rows) {
      y -= 14;
      text(r.slice(0, 44), L + i * w, 10);
    }
    low = Math.min(low, y);
  });
  y = low - 22;
  if (inv.periodStart) {
    text(`${KIND[inv.kind] ?? "Invoice"} · ${day(inv.periodStart)} – ${day(inv.periodEnd)}`, L, 10, soft);
    y -= 22;
  }
  text("Description", L, 9, soft);
  text("Amount", R, 9, soft, true);
  y -= 16;
  rule();
  for (const l of inv.lines) {
    text(l.label.slice(0, 80), L, 10.5);
    text(l.amount < 0 ? `−${money(-l.amount, inv.currency)}` : money(l.amount, inv.currency), R, 10.5, l.amount < 0 ? soft : ink, true);
    y -= 18;
  }
  y -= 4;
  rule();
  const sum = (k: string, v: string, size = 10.5) => {
    text(k, R - 200, size, size > 11 ? ink : soft);
    text(v, R, size, ink, true);
    y -= size > 11 ? 22 : 16;
  };
  sum("Subtotal", money(inv.subtotal, inv.currency));
  sum(`${inv.taxLabel} ${inv.taxBps / 100}%`, money(inv.tax, inv.currency));
  y -= 4;
  sum(inv.status === "paid" ? "Total paid" : "Total", money(inv.total, inv.currency), 13);
  y -= 24;
  text("Amounts in Indian rupees. This receipt is generated by Cloudesk and needs no signature.", L, 8.5, soft);
  if (seller.email) {
    y -= 13;
    text(`Questions about this invoice: ${seller.email}`, L, 8.5, soft);
  }
  return pdf.save();
}

/** The same receipt as plain text, for the email body. */
export function receiptText(inv: Invoice, number: string, buyer: string) {
  const pad = (a: string, b: string) => `${a}${" ".repeat(Math.max(2, 46 - a.length - b.length))}${b}`;
  return [
    `Thank you — we've received your payment for ${buyer}.`,
    "",
    `${number} · ${inv.description}`,
    `Paid ${day(inv.paidAt)}${inv.paidVia ? ` via ${VIA[inv.paidVia] ?? inv.paidVia}` : ""}${inv.paymentRef && inv.paidVia !== "credit" ? ` (${inv.paymentRef})` : ""}`,
    ...(inv.periodStart ? [`Period ${day(inv.periodStart)} – ${day(inv.periodEnd)}`] : []),
    "",
    ...inv.lines.map((l) => pad(l.label, l.amount < 0 ? `−${money(-l.amount, inv.currency)}` : money(l.amount, inv.currency))),
    "",
    pad("Subtotal", money(inv.subtotal, inv.currency)),
    pad(`${inv.taxLabel} ${inv.taxBps / 100}%`, money(inv.tax, inv.currency)),
    pad("Total paid", money(inv.total, inv.currency)),
    "",
    "The receipt (a PDF tax invoice) is attached. Every invoice is also in Settings → Billing:",
    appUrl("/settings/billing"),
  ].join("\n");
}

/** Emails the receipt for a paid invoice to the workspace's owners and billing people. */
export async function sendReceipt(inv: Invoice, number: string) {
  const [org] = await db.select({ name: schema.organizations.name }).from(schema.organizations).where(eq(schema.organizations.id, inv.orgId));
  const to = await db.select({ email: schema.users.email }).from(schema.memberships).innerJoin(schema.users, eq(schema.users.id, schema.memberships.userId)).where(and(eq(schema.memberships.orgId, inv.orgId), inArray(schema.memberships.role, ["owner", "billing"])));
  if (!to.length) return 0;
  const legal = (await settings()).legal;
  const buyer = org?.name ?? "your workspace";
  const pdf = Buffer.from(await receiptPdf(inv, number, buyer, { name: legal.companyName, address: legal.registeredAddress, gstin: legal.gstin, email: legal.contactEmail })).toString("base64");
  const body = receiptText(inv, number, buyer);
  for (const u of to) await sendMail({ to: u.email, subject: `Receipt ${number} — ${money(inv.total, inv.currency)} paid`, body, fromName: "Cloudesk", attachments: [{ filename: `${number}.pdf`, contentType: "application/pdf", base64: pdf }] });
  return to.length;
}
