"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Copy, Download, KeyRound, ShieldCheck } from "lucide-react";
import { useRouter, useSearchParams } from "next/navigation";
import { useEffect, useState } from "react";
import { GithubMark } from "@/components/github-button";
import { Dialog, useToast } from "@/components/ui/overlays";
import { Badge, Button, Card, Field, Input, Notice } from "@/components/ui/primitives";
import { api, errorMessage } from "@/lib/client/api";
import { timeAgo } from "@/lib/client/format";

export type MfaStatus = { enabled: boolean; enabledAt: string | null; recoveryCodesLeft: number; hasPassword: boolean };

export function useMfaStatus() {
  return useQuery({ queryKey: ["mfa"], queryFn: () => api<MfaStatus>("/api/v1/auth/mfa") });
}

function RecoveryCodes({ codes }: { codes: string[] }) {
  const toast = useToast();
  const text = codes.join("\n");
  return (
    <div className="space-y-3">
      <Notice tone="warning" title="Save these recovery codes now">
        Each code works once if you lose your phone. They won&apos;t be shown again.
      </Notice>
      <ol className="grid grid-cols-2 gap-1.5 rounded-[var(--radius-lg)] bg-surface-2 p-4 font-mono text-[13px]">
        {codes.map((c) => (
          <li key={c}>{c}</li>
        ))}
      </ol>
      <div className="flex gap-2">
        <Button size="sm" icon={<Copy className="size-3.5" />} onClick={() => navigator.clipboard.writeText(text).then(() => toast({ tone: "success", title: "Copied" }))}>
          Copy
        </Button>
        <Button
          size="sm"
          icon={<Download className="size-3.5" />}
          onClick={() => {
            const a = document.createElement("a");
            a.href = URL.createObjectURL(new Blob([`Cloudesk recovery codes\n\n${text}\n`], { type: "text/plain" }));
            a.download = "cloudesk-recovery-codes.txt";
            a.click();
            URL.revokeObjectURL(a.href);
          }}
        >
          Download
        </Button>
      </div>
    </div>
  );
}

function SetupDialog({ open, onClose }: { open: boolean; onClose: () => void }) {
  const qc = useQueryClient();
  const router = useRouter();
  const [code, setCode] = useState("");
  const [codes, setCodes] = useState<string[] | null>(null);
  const setup = useMutation({ mutationFn: () => api<{ secret: string; url: string; qr: string }>("/api/v1/auth/mfa/setup", { method: "POST", body: {} }) });
  const enable = useMutation({
    mutationFn: () => api<{ recoveryCodes: string[] }>("/api/v1/auth/mfa/enable", { method: "POST", body: { code } }),
    onSuccess: (r) => {
      setCodes(r.recoveryCodes);
      qc.invalidateQueries({ queryKey: ["mfa"] });
    },
  });
  const start = setup.mutate;
  useEffect(() => {
    if (open) start();
  }, [open, start]);
  const close = () => {
    // Refresh so the session (and any "two-factor required" banner) updates.
    if (codes) router.refresh();
    setCode("");
    setCodes(null);
    onClose();
  };
  return (
    <Dialog open={open} onClose={close} title={codes ? "Two-factor sign-in is on" : "Set up two-factor sign-in"} description={codes ? undefined : "Scan the code with an authenticator app such as Apple Passwords, Google Authenticator, 1Password or Authy."} footer={codes ? <Button variant="primary" onClick={close}>I&apos;ve saved my codes</Button> : undefined}>
      {codes ? (
        <RecoveryCodes codes={codes} />
      ) : setup.data ? (
        <form
          className="grid gap-5 sm:grid-cols-[180px_1fr]"
          onSubmit={(e) => {
            e.preventDefault();
            enable.mutate();
          }}
        >
          {/* The SVG is generated by our server from the otpauth link. */}
          <div className="rounded-[var(--radius-lg)] bg-white p-2 [&_svg]:h-auto [&_svg]:w-full" dangerouslySetInnerHTML={{ __html: setup.data.qr }} aria-label="QR code for your authenticator app" role="img" />
          <div className="grid content-start gap-3">
            <p className="text-[13px] text-muted">
              Can&apos;t scan? Enter this key: <code className="block break-all rounded-md bg-surface-2 px-2 py-1 font-mono text-[12px] text-fg">{setup.data.secret.match(/.{1,4}/g)?.join(" ")}</code>
            </p>
            <Field label="6-digit code" error={enable.error ? errorMessage(enable.error) : undefined}>
              {(p) => <Input {...p} value={code} onChange={(e) => setCode(e.target.value)} inputMode="numeric" autoComplete="one-time-code" placeholder="123 456" maxLength={7} className="font-mono tracking-[0.2em]" autoFocus />}
            </Field>
            <Button type="submit" variant="primary" loading={enable.isPending} disabled={code.replace(/\s/g, "").length !== 6}>
              Turn on
            </Button>
          </div>
        </form>
      ) : setup.error ? (
        <Notice tone="danger">{errorMessage(setup.error)}</Notice>
      ) : (
        <div className="skeleton h-44 rounded-[var(--radius-lg)]" aria-hidden />
      )}
    </Dialog>
  );
}

export function SecurityCard() {
  const qc = useQueryClient();
  const toast = useToast();
  const params = useSearchParams();
  const mfa = useMfaStatus();
  const conns = useQuery({ queryKey: ["connections"], queryFn: () => api<{ githubAvailable: boolean; connections: { provider: string; login: string; createdAt: string }[] }>("/api/v1/auth/connections") });
  const [setupOpen, setSetupOpen] = useState(false);
  const [disableOpen, setDisableOpen] = useState(false);
  const [proof, setProof] = useState("");
  const [regenCode, setRegenCode] = useState("");
  const [newCodes, setNewCodes] = useState<string[] | null>(null);
  const disable = useMutation({
    mutationFn: () => api("/api/v1/auth/mfa/disable", { method: "POST", body: mfa.data?.hasPassword ? { password: proof } : { code: proof } }),
    onSuccess: () => {
      setDisableOpen(false);
      setProof("");
      qc.invalidateQueries({ queryKey: ["mfa"] });
      toast({ tone: "success", title: "Two-factor sign-in turned off" });
    },
  });
  const regen = useMutation({
    mutationFn: () => api<{ recoveryCodes: string[] }>("/api/v1/auth/mfa/recovery-codes", { method: "POST", body: { code: regenCode } }),
    onSuccess: (r) => {
      setNewCodes(r.recoveryCodes);
      setRegenCode("");
      qc.invalidateQueries({ queryKey: ["mfa"] });
    },
    onError: (e) => toast({ tone: "error", title: "Could not make new codes", description: errorMessage(e) }),
  });
  const disconnect = useMutation({
    mutationFn: () => api("/api/v1/auth/connections", { method: "DELETE" }),
    onSuccess: () => qc.invalidateQueries({ queryKey: ["connections"] }),
    onError: (e) => toast({ tone: "error", title: "Could not disconnect", description: errorMessage(e) }),
  });
  const github = conns.data?.connections.find((c) => c.provider === "github");
  const flash = params.get("github") === "connected" ? "GitHub connected." : params.get("error");

  return (
    <Card className="p-5">
      <div className="flex items-center gap-2">
        <ShieldCheck className="size-4" aria-hidden />
        <h2 className="text-sm font-semibold">Security</h2>
      </div>
      {flash && (
        <div className="mt-3">
          <Notice tone={params.get("error") ? "danger" : "success"}>{flash}</Notice>
        </div>
      )}
      <div className="mt-4 grid gap-4 md:grid-cols-2">
        <div className="rounded-[var(--radius-lg)] border border-border p-4">
          <div className="flex items-center justify-between gap-2">
            <p className="flex items-center gap-2 text-[13px] font-medium">
              <KeyRound className="size-4 text-muted" aria-hidden /> Two-factor sign-in
            </p>
            {mfa.data?.enabled ? <Badge tone="success">On</Badge> : <Badge>Off</Badge>}
          </div>
          <p className="mt-1 text-xs text-muted">{mfa.data?.enabled ? `On since ${timeAgo(mfa.data.enabledAt!)} · ${mfa.data.recoveryCodesLeft} recovery codes left` : "Ask for a code from your phone when signing in."}</p>
          <div className="mt-3 flex flex-wrap gap-2">
            {mfa.data?.enabled ? (
              <>
                <form
                  className="flex gap-1.5"
                  onSubmit={(e) => {
                    e.preventDefault();
                    regen.mutate();
                  }}
                >
                  <Input aria-label="Current code" value={regenCode} onChange={(e) => setRegenCode(e.target.value)} placeholder="Code" className="!h-8 w-24 font-mono" inputMode="numeric" />
                  <Button size="sm" type="submit" loading={regen.isPending} disabled={regenCode.length < 6}>
                    New recovery codes
                  </Button>
                </form>
                <Button size="sm" variant="ghost" onClick={() => setDisableOpen(true)}>
                  Turn off
                </Button>
              </>
            ) : (
              <Button size="sm" variant="primary" onClick={() => setSetupOpen(true)}>
                Set up
              </Button>
            )}
          </div>
        </div>
        <div className="rounded-[var(--radius-lg)] border border-border p-4">
          <div className="flex items-center justify-between gap-2">
            <p className="flex items-center gap-2 text-[13px] font-medium">
              <GithubMark /> GitHub
            </p>
            {github ? <Badge tone="success">@{github.login}</Badge> : <Badge>Not connected</Badge>}
          </div>
          <p className="mt-1 text-xs text-muted">{conns.data && !conns.data.githubAvailable ? "GitHub sign-in isn't configured on this platform yet." : "Sign in with your GitHub account."}</p>
          <div className="mt-3">
            {github ? (
              <Button size="sm" variant="ghost" loading={disconnect.isPending} onClick={() => disconnect.mutate()}>
                Disconnect
              </Button>
            ) : (
              conns.data?.githubAvailable && (
                <a href="/api/v1/auth/github/start?mode=link" className="inline-flex h-7 items-center gap-1.5 rounded-full border border-border px-3 text-[13px] font-medium hover:bg-surface-2">
                  <GithubMark /> Connect
                </a>
              )
            )}
          </div>
        </div>
      </div>
      <SetupDialog open={setupOpen} onClose={() => setSetupOpen(false)} />
      <Dialog open={!!newCodes} onClose={() => setNewCodes(null)} title="New recovery codes" description="Your old codes no longer work." footer={<Button variant="primary" onClick={() => setNewCodes(null)}>Done</Button>}>
        {newCodes && <RecoveryCodes codes={newCodes} />}
      </Dialog>
      <Dialog
        open={disableOpen}
        onClose={() => setDisableOpen(false)}
        size="sm"
        title="Turn off two-factor sign-in?"
        description="Your account will be protected by your password only."
        footer={
          <>
            <Button onClick={() => setDisableOpen(false)}>Cancel</Button>
            <Button variant="danger" loading={disable.isPending} disabled={!proof} onClick={() => disable.mutate()}>
              Turn off
            </Button>
          </>
        }
      >
        <Field label={mfa.data?.hasPassword ? "Your password" : "A current code"} error={disable.error ? errorMessage(disable.error) : undefined}>
          {(p) => <Input {...p} type={mfa.data?.hasPassword ? "password" : "text"} value={proof} onChange={(e) => setProof(e.target.value)} autoFocus />}
        </Field>
      </Dialog>
    </Card>
  );
}

/** Recent sign-ins to this account, so anything unexpected stands out. */
export function SignInsCard() {
  const q = useQuery({ queryKey: ["my-logins"], queryFn: () => api<{ logins: { id: string; ok: boolean; method: string; reason: string; ip: string | null; userAgent: string | null; newDevice: boolean; at: string }[] }>("/api/v1/auth/logins") });
  const rows = q.data?.logins ?? [];
  return (
    <Card className="p-5">
      <h2 className="text-[15px] font-semibold">Recent sign-ins</h2>
      <p className="mt-0.5 text-[13px] text-muted">We email you when your account is signed in to from a new browser or network.</p>
      {!rows.length ? <p className="mt-3 text-[13px] text-muted">None recorded yet.</p> : (
        <ul className="mt-3 divide-y divide-border text-[13px]">
          {rows.slice(0, 15).map((l) => (
            <li key={l.id} className="flex flex-wrap items-center justify-between gap-2 py-2">
              <span className="min-w-0"><b className="font-medium">{new Date(l.at).toLocaleString("en-IN", { timeZone: "Asia/Kolkata", dateStyle: "medium", timeStyle: "short" })}</b> <span className="text-muted">· {l.method} · {l.ip ?? "unknown address"} · {(l.userAgent ?? "").slice(0, 60)}</span></span>
              <span className="flex gap-1.5">{l.newDevice && <Badge tone="warning">New device</Badge>}<Badge tone={l.ok ? "success" : "danger"}>{l.ok ? "Signed in" : `Failed${l.reason ? `: ${l.reason}` : ""}`}</Badge></span>
            </li>
          ))}
        </ul>
      )}
    </Card>
  );
}
