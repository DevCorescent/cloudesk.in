export function photoUrl(id: string, width = 1600, ratio?: [number, number]) {
  const h = ratio ? `&h=${Math.round((width * ratio[1]) / ratio[0])}` : "";
  return `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=${width}${h}&q=80`;
}

export const isPlaceholderPhoto = (url: unknown) => typeof url === "string" && PHOTOS.some((p) => url.includes(p.id));

/**
 * Picks up to `count` photos that match the tags, best matches first and
 * deterministic for a seed. Never pads with off-topic photos.
 */
export function pickPhotos(tags: string[], count: number, seed = 0): Photo[] {
  return PHOTOS.map((p, i) => ({ p, m: p.tags.filter((t) => tags.includes(t)).length, r: (i * 7 + seed * 13) % 97 }))
    .filter((x) => x.m > 0)
    .sort((a, b) => b.m - a.m || a.r - b.r)
    .slice(0, count)
    .map((x) => x.p);
}
